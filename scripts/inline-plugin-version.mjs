// scripts/inline-plugin-version.mjs
//
// v0.2.131 — bake manifest.json's version string into main.js at
// build time. Per v0331 §2.1: the plugin's TypeScript source needs
// a constant that becomes part of compiled main.js. At onload, the
// plugin compares this baked-in constant against the manifest.json
// it reads off disk; mismatch → Notice + console.error so cohort
// users with stale BRAT installs see clear instructions instead of
// silently running old code.
//
// Mirrors the v0.2.98 inlined-asset version stamping discipline
// (B10 in the constitution): every release's compiled main.js
// carries its own self-claimed version.
//
// Output: src/version-constant.generated.ts (gitignore-friendly;
// regenerated on every build).
//
// Drain 2026-10-09-2200 (rider d): CCQA noted "the version string is not a build identifier" — three different builds all reported
// v0.6.1. The same script now also writes src/build-stamp.generated.ts (GITIGNORED, regenerated every build): the short git SHA of
// HEAD, whether the working tree had uncommitted changes to tracked files, and the build time. It is shown in the status-bar tooltip and in
// Settings -> Forge Actions (Beta). Never throws: outside a git checkout the SHA is "unknown".
//
// Usage:
//   node scripts/inline-plugin-version.mjs

import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const manifestPath = path.join(ROOT, "manifest.json");
const outPath = path.join(ROOT, "src", "version-constant.generated.ts");
const stampPath = path.join(ROOT, "src", "build-stamp.generated.ts");

/** Short SHA of HEAD + "dirty" (tracked files differ from HEAD), or {sha: "unknown"} outside a git checkout. */
export function readGitStamp(cwd = ROOT, run = (args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] })) {
  try {
    const sha = String(run(["rev-parse", "--short=9", "HEAD"])).trim();
    if (!/^[0-9a-f]{7,40}$/.test(sha)) return { sha: "unknown", dirty: false };
    let dirty = false;
    try { dirty = String(run(["status", "--porcelain", "--untracked-files=no"])).trim().length > 0; } catch { /* unknown -> not dirty */ }
    return { sha, dirty };
  } catch {
    return { sha: "unknown", dirty: false };
  }
}

/** The text of src/build-stamp.generated.ts. */
export function renderBuildStamp({ sha, dirty, builtAt }) {
  return `// AUTO-GENERATED by scripts/inline-plugin-version.mjs at build time. GITIGNORED. Do not edit.
// Drain 2026-10-09-2200 (rider d): a build identifier (the version string alone is not one).

export const BUILD_STAMP = ${JSON.stringify({ sha, dirty, builtAt })} as const;
`;
}

function main() {
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const version = manifest.version;

if (typeof version !== "string" || version.length === 0) {
  console.error(
    "[inline-plugin-version] manifest.json missing or empty 'version' field",
  );
  process.exit(1);
}

const contents = `// AUTO-GENERATED by scripts/inline-plugin-version.mjs at build time.
// Do not edit by hand. Source of truth is manifest.json's "version" field.
//
// v0.2.131 — baked into main.js so onload can self-check against the
// on-disk manifest.json. Stale-install detection per v0331.

export const PLUGIN_VERSION_AT_BUILD = ${JSON.stringify(version)};
`;

fs.writeFileSync(outPath, contents, "utf8");
console.log(`[inline-plugin-version] wrote ${path.relative(ROOT, outPath)} → ${version}`);

const stamp = { ...readGitStamp(), builtAt: new Date().toISOString() };
fs.writeFileSync(stampPath, renderBuildStamp(stamp), "utf8");
console.log(`[inline-plugin-version] wrote ${path.relative(ROOT, stampPath)} → ${stamp.sha}${stamp.dirty ? "+dirty" : ""} ${stamp.builtAt}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
