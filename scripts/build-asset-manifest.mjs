// scripts/build-asset-manifest.mjs
//
// BRAT Phase 1, part (a) — drain 2026-08-19-0900.
//
// Bakes a filename → sha256 map for every HYDRATABLE binary asset into
// main.js, so the verifier ships inside the thing BRAT installs. A BRAT
// vault gets only main.js + manifest.json + styles.css; the binaries are
// fetched at runtime from this version's own GitHub release assets. The
// baked hashes are what make that fetch safe: an artifact that does not
// match is deleted, never executed (§8).
//
// Hydratable = the two buckets Phase 0 classified as (b): assets/wheels/
// (11 files) and assets/pyodide/ (9 files). Everything else under
// assets/ is already inlined as text via inline-bundled-assets.mjs and
// needs no download.
//
// Keys are RELEASE-ASSET names (basenames), not vault-relative paths,
// because `gh release create` flattens paths on upload and the fetch URL
// is `.../releases/download/v<version>/<basename>`. A basename collision
// across the two directories would therefore be a real ambiguity at
// fetch time, so it is a hard error here rather than a silent overwrite.
//
// Mirrors inline-plugin-version.mjs: gitignored output, regenerated on
// every build, never hand-edited.
//
// Usage:
//   node scripts/build-asset-manifest.mjs

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

/** The (b)-bucket directories, relative to assets/. */
export const HYDRATABLE_DIRS = ["wheels", "pyodide"];

export function sha256(buf) {
  return crypto.createHash("sha256").update(buf).digest("hex");
}

/** Build the manifest entries by reading `assetsRoot`.
 *
 *  Returns entries sorted by name so the generated file is byte-stable
 *  across machines and runs — a manifest that reordered itself would
 *  produce a spurious main.js diff on every build.
 */
export function buildEntries(assetsRoot) {
  const byName = new Map();
  for (const dir of HYDRATABLE_DIRS) {
    const abs = path.join(assetsRoot, dir);
    if (!fs.existsSync(abs)) continue;
    for (const fname of fs.readdirSync(abs).sort()) {
      const full = path.join(abs, fname);
      if (!fs.statSync(full).isFile()) continue;
      if (byName.has(fname)) {
        throw new Error(
          `asset-manifest: basename collision on ${fname} — ` +
          `${byName.get(fname).dir}/ and ${dir}/ both provide it. ` +
          `Release assets are flat, so this is ambiguous at fetch time.`,
        );
      }
      const bytes = fs.readFileSync(full);
      byName.set(fname, {
        name: fname,
        dir,
        relpath: `${dir}/${fname}`,
        sha256: sha256(bytes),
        bytes: bytes.length,
      });
    }
  }
  return [...byName.values()].sort((a, b) => (a.name < b.name ? -1 : 1));
}

export function renderModule(entries) {
  const total = entries.reduce((s, e) => s + e.bytes, 0);
  const lines = entries.map(
    (e) => `  ${JSON.stringify(e.name)}: ` +
      `{ relpath: ${JSON.stringify(e.relpath)}, ` +
      `sha256: ${JSON.stringify(e.sha256)}, bytes: ${e.bytes} },`,
  );
  return `// AUTO-GENERATED by scripts/build-asset-manifest.mjs at build time.
// Do not edit by hand. Source of truth is the files under assets/.
//
// BRAT Phase 1 (drain 2026-08-19-0900): filename → sha256 for every
// binary asset a BRAT install must fetch from this version's own GitHub
// release. Baked into main.js so the verifier travels with the plugin.

export interface HydratableAsset {
  /** Path under assets/ where this file lives once hydrated. */
  relpath: string;
  /** Lowercase hex sha256 of the file's bytes. */
  sha256: string;
  /** Exact byte length — lets progress UX total the download up front. */
  bytes: number;
}

/** Keyed by RELEASE-ASSET name (basename), because release assets are
 *  flat and the fetch URL ends in that basename. */
export const HYDRATABLE_ASSETS: Record<string, HydratableAsset> = {
${lines.join("\n")}
};

/** Total bytes of a full cold hydration. */
export const HYDRATABLE_TOTAL_BYTES = ${total};
`;
}

function main() {
  const assetsRoot = path.join(ROOT, "assets");
  const outPath = path.join(ROOT, "src", "asset-manifest.generated.ts");
  const entries = buildEntries(assetsRoot);

  if (entries.length === 0) {
    console.error(
      "[build-asset-manifest] refusing to write an EMPTY manifest — " +
      "assets/wheels/ and assets/pyodide/ are both missing or empty. " +
      "An empty manifest would make the hydrator believe there is " +
      "nothing to download and boot a BRAT install with no runtime.",
    );
    process.exit(1);
  }

  fs.writeFileSync(outPath, renderModule(entries), "utf8");
  const mb = (entries.reduce((s, e) => s + e.bytes, 0) / 1048576).toFixed(2);
  console.log(
    `[build-asset-manifest] wrote ${path.relative(ROOT, outPath)} → ` +
    `${entries.length} assets, ${mb} MB`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) main();
