// score_first M7b (a) (drain 2026-10-26-1260, DEMO profile) — "Refresh note links": every phrase note (`phrases/phrase_NNN.md`) and bar note (`bars/bar_NNN.md`) of the vault brought up to date with what the json says
// (phrase-core.ts refreshPhraseNoteText, phrase-notes-core.ts refreshBarNoteText). Pure: the vault is injected. It reads each note first and writes ONLY a note that would change (so a second run touches nothing: no write, no
// modify event, no byte), the write itself re-derives from the note's CURRENT text inside one atomic read-modify-write, and a note it cannot read is a line naming why, never a throw and never a change.
import { refreshPhraseNoteText } from './phrase-core.ts';
import { refreshBarNoteText } from './phrase-notes-core.ts';
import { refreshKitNoteText } from './kit-core.ts';
import { refreshArrangementNoteText } from './arrangement-core.ts';

export interface RefreshNotesPorts {
  /** The notes to look at: `{ path, name }` for every `phrases/phrase_NNN.md` and `bars/bar_NNN.md` (never README.md). */
  phrases(): Array<{ path: string; name: string }>;
  bars(): Array<{ path: string; name: string }>;
  /** 2026-10-29-0820: the kit notes (`kits/<name>.md`) and arrangement notes (`arrangements/<name>.md`), when the vault has them (README.md never). Absent = those are not looked at, and the summary and its lines are exactly what they were. */
  kits?(): Array<{ path: string; name: string }>;
  arrangements?(): Array<{ path: string; name: string }>;
  read(path: string): Promise<string>;
  /** One atomic read-modify-write of the note: `fn` gets the CURRENT text and returns the new one. */
  process(path: string, fn: (current: string) => string): Promise<void>;
}

export interface RefreshSummary {
  phrases: { total: number; updated: number; current: number; skipped: string[] };
  bars: { total: number; updated: number; current: number; keptAsWritten: number; skipped: string[] };
  kits?: { total: number; updated: number; current: number; skipped: string[] };
  arrangements?: { total: number; updated: number; current: number; skipped: string[] };
}

type Plain = { total: number; updated: number; current: number; skipped: string[] };
/** The same loop for a note kind whose derived text is regenerated by `refresh` (kits, arrangements): read first, write only a note that would change, a note it cannot read is a line. */
async function refreshKind(ports: RefreshNotesPorts, notes: Array<{ path: string; name: string }>, refresh: (text: string, name: string) => { ok: true; text: string; changed: boolean } | { ok: false; message: string }): Promise<Plain> {
  const sum: Plain = { total: 0, updated: 0, current: 0, skipped: [] };
  for (const { path, name } of notes) {
    sum.total++;
    try {
      const r = refresh(await ports.read(path), name);
      if (r.ok === false) { sum.skipped.push(`${path}: ${r.message}`); continue; }
      if (!r.changed) { sum.current++; continue; }
      await ports.process(path, (cur) => { const again = refresh(cur, name); return again.ok ? again.text : cur; });
      sum.updated++;
    } catch (e) { sum.skipped.push(`${path}: ${(e as Error)?.message ?? e}`); }
  }
  return sum;
}

export async function refreshNoteLinks(ports: RefreshNotesPorts): Promise<RefreshSummary> {
  const sum: RefreshSummary = { phrases: { total: 0, updated: 0, current: 0, skipped: [] }, bars: { total: 0, updated: 0, current: 0, keptAsWritten: 0, skipped: [] } };
  for (const { path, name } of ports.phrases()) {
    sum.phrases.total++;
    try {
      const r = refreshPhraseNoteText(await ports.read(path), name);
      if (r.ok === false) { sum.phrases.skipped.push(`${path}: ${r.message}`); continue; }
      if (!r.changed) { sum.phrases.current++; continue; }
      await ports.process(path, (cur) => { const again = refreshPhraseNoteText(cur, name); return again.ok ? again.text : cur; });
      sum.phrases.updated++;
    } catch (e) { sum.phrases.skipped.push(`${path}: ${(e as Error)?.message ?? e}`); }
  }
  for (const { path, name } of ports.bars()) {
    sum.bars.total++;
    try {
      const r = refreshBarNoteText(await ports.read(path), name);
      if (r.ok === false) { sum.bars.skipped.push(`${path}: ${r.message}`); continue; }
      if (r.kept) sum.bars.keptAsWritten++;
      if (!r.changed) { sum.bars.current++; continue; }
      await ports.process(path, (cur) => { const again = refreshBarNoteText(cur, name); return again.ok ? again.text : cur; });
      sum.bars.updated++;
    } catch (e) { sum.bars.skipped.push(`${path}: ${(e as Error)?.message ?? e}`); }
  }
  if (ports.kits) sum.kits = await refreshKind(ports, ports.kits(), (text) => refreshKitNoteText(text));
  if (ports.arrangements) sum.arrangements = await refreshKind(ports, ports.arrangements(), refreshArrangementNoteText);
  return sum;
}

/** The evidence line (`[forge-notes] ...`) and the one-line Notice of a run. */
export function refreshLine(s: RefreshSummary): string {
  const skipped = s.phrases.skipped.length + s.bars.skipped.length + (s.kits?.skipped.length ?? 0) + (s.arrangements?.skipped.length ?? 0);
  const more = (label: string, k: Plain | undefined): string => (k ? `, ${label} ${k.total} (${k.updated} updated, ${k.current} already current)` : '');
  return `[forge-notes] refresh note links: phrases ${s.phrases.total} (${s.phrases.updated} updated, ${s.phrases.current} already current), bars ${s.bars.total} (${s.bars.updated} updated, ${s.bars.current} already current, ${s.bars.keptAsWritten} descriptions left as written)${more('kits', s.kits)}${more('arrangements', s.arrangements)}${skipped > 0 ? `, ${skipped} skipped` : ''}`;
}
export function refreshNotice(s: RefreshSummary): string {
  const extra = (s.kits?.updated ?? 0) + (s.arrangements?.updated ?? 0);
  const n = s.phrases.updated + s.bars.updated + extra;
  const skipped = [...s.phrases.skipped, ...s.bars.skipped, ...(s.kits?.skipped ?? []), ...(s.arrangements?.skipped ?? [])];
  const changed = `${s.phrases.updated} phrase note(s) and ${s.bars.updated} bar note(s) updated${extra > 0 ? ` (and ${s.kits?.updated ?? 0} kit note(s), ${s.arrangements?.updated ?? 0} arrangement note(s))` : ''}`;
  return `Refresh note links: ${n === 0 ? 'every note was already up to date' : changed}${skipped.length > 0 ? `; ${skipped.length} could not be read (${skipped[0]})` : ''}.`;
}
